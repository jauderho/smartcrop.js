// Pack a trained saliency model (bench/jssal/train.ts output) into
// src/saliency-weights.ts: weights and biases as base64 float16, mean/std f32.
// Usage: bun bench/jssal/pack.ts <model.json> [--out src/saliency-weights.ts]
import { join } from 'node:path';
import { encodeF16 } from '../../src/learned';
import type { SaliencyModel } from '../../src/saliency';

const src = process.argv[2];
const i = process.argv.indexOf('--out');
const out =
  i > -1
    ? process.argv[i + 1]
    : join(import.meta.dir, '../../src/saliency-weights.ts');
const pack = (m: SaliencyModel): unknown => ({
  ...(m.context ? { context: pack(m.context) } : {}),
  mean: m.mean,
  std: m.std,
  layers: m.layers.map((l) => ({
    inDim: l.inDim,
    outDim: l.outDim,
    w: encodeF16(l.w),
    b: encodeF16(l.b),
  })),
});
const model: SaliencyModel = await Bun.file(src).json();
await Bun.write(
  out,
  `// Generated by bench/jssal/pack.ts from ${src.split('/').pop()}: the pure-JS\n// saliency model (src/saliency.ts), distilled from U2-Netp.\nimport type { PackedSaliencyModel } from './saliency';\n\nexport const SALIENCY_PACKED: PackedSaliencyModel = ${JSON.stringify(pack(model))};\n`
);
console.log(`wrote ${out}`);
